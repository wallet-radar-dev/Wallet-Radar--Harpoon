#!/usr/bin/env bash
# Щоденне оновлення сигналів по РЕАЛЬНИХ КИТАХ — групах із найбільшим капіталом.
#
# ЩО ЗМІНИЛОСЯ 31.08.2026. Раніше тут працювали rgflow/rgphase/rgfund/rgsync. Вони
# фільтрували групи за ідентифікатором CAP:* і читали поле commonAssets — тобто модель
# «група на актив». З 22.07.2026 такої моделі в даних немає: групи стали розбиттям
# гаманців (NET/HUB/NET-WEAK/CG*), поля commonAssets не існує. Біни перестали знаходити
# бодай одну групу, а 22.08 записали цю порожнечу поверх власних датасетів і відзвітували
# «done». Їхні вихідні файли не читав ніхто, крім них самих.
#
# Тепер працює groupsig — він рахує те, заради чого все й робиться: контроль емісії,
# реальну можливість вийти за ліквідністю пулів і фазу набору/роздачі по КОЖНОМУ токену
# групи. Запускаємо його лише на китах: решта 70 груп мають ~$0 реального капіталу.
set -uo pipefail
ROOT=/opt/wallet-tracker
LOG=$ROOT/deploy/capgroups-refresh.log
cd "$ROOT"

# Кити за реальним капіталом (нативний ETH + реалізовна частина токенів):
#   HUB      $2.35 млрд    78 гаманців
#   NET      ~$901 млн   6864
#   NET-WEAK ~$900 млн  54497
# Перелік свідомо явний, а не «топ-N автоматом»: склад китів має мінятися рішенням,
# а не тихо через зсув однієї цифри.
WHALES="${WHALES:-HUB NET NET-WEAK}"

for g in $WHALES; do
  echo "$(date -u +%FT%TZ) groupsig $g" >> "$LOG"
  timeout 2400 ./backfill/target/release/groupsig "$ROOT" "$g" >> "$LOG" 2>&1
  rc=$?
  [ $rc -ne 0 ] && echo "$(date -u +%FT%TZ) ⚠️ groupsig $g завершився кодом $rc" >> "$LOG"
done

APP_ROOT=$ROOT ./backfill/target/release/distrib-alert "$ROOT" >> "$LOG" 2>&1
echo "$(date -u +%FT%TZ) capgroups-refresh done" >> "$LOG"
