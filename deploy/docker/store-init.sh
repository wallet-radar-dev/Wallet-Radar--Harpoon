#!/bin/sh
# Разова ініціалізація бази довідників (сервіс store-init у docker-compose.yml).
#
# ГОЛОВНЕ ПРАВИЛО: цей скрипт НІКОЛИ не змінює, не перезаписує й не видаляє наявну базу.
# Він лише СТВОРЮЄ її, коли за шляхом $WR_DB нічого немає. Як це гарантовано:
#   * наявний файл (навіть порожній чи биткий симлінк) → вихід без жодної дії або з відмовою;
#   * осиротілі $WR_DB-wal / -shm / -journal без основного файла → ВІДМОВА: це або реальна
#     база, яку перенесли/пошкодили, або незавершений запис; свіжа база поряд їх би осиротила;
#   * нову базу будують під тимчасовим іменем і публікують через `ln` — він не перезаписує
#     (падає, якщо ціль уже є), тож навіть гонка двох запусків не затре чужу базу, а
#     обірваний запуск лишає сміття лише під тимчасовим іменем, а не напівготову "базу".
#
# Джерела нової бази, за пріоритетом:
#   1) $WR_SEED/wallet-radar.db   — готова база від авторів → копіюється;
#   2) $WR_SEED/constants.json    — seed-файли авторів → `wr-import load`;
#   3) нічого                     — порожня база з міграціями (`wr-import init`).
set -eu

db="$WR_DB"
tmp="$db.tmp.$$"

log()  { echo "[store-init] $*"; }
warn() { echo "[store-init] $*" >&2; }
die()  { warn "ВІДМОВА: $*"; exit 1; }

cleanup() { rm -f "$tmp" "$tmp-wal" "$tmp-shm" "$tmp-journal"; }
trap cleanup EXIT

# --- 1. Що вже лежить за шляхом? Нічого не чіпаємо ---------------------------------------
if [ -e "$db" ] || [ -L "$db" ]; then
  if [ -f "$db" ] && [ -s "$db" ]; then
    log "$db вже є ($(wc -c < "$db") байт) — нічого не роблю"
    exit 0
  fi
  die "$db існує, але це не непорожній файл (порожній файл, симлінк або тека). Я його не чіпаю — розберіться вручну."
fi

for side in "$db-wal" "$db-shm" "$db-journal"; do
  if [ -e "$side" ] || [ -L "$side" ]; then
    die "основного файла $db немає, але лежить $side. Схоже, базу перенесли або пошкодили. Нову базу не створюю, щоб не осиротити ці дані."
  fi
done

# Залишки обірваного попереднього запуску — лише наші тимчасові імена, основний файл тут не фігурує.
for stale in "$db".tmp.*; do
  [ -e "$stale" ] && rm -f "$stale"
done

# --- 2. Будуємо нову базу під тимчасовим іменем ------------------------------------------
if [ -f "$WR_SEED/wallet-radar.db" ]; then
  log "копіюю готову базу з $WR_SEED/wallet-radar.db"
  cp "$WR_SEED/wallet-radar.db" "$tmp"
elif [ -f "$WR_SEED/constants.json" ]; then
  log "наповнюю з seed-файлів $WR_SEED (wr-import load)"
  WR_DB="$tmp" wr-import load
else
  warn "УВАГА: seed не знайдено в $WR_SEED — створюю ПОРОЖНЮ базу."
  warn "UI працюватиме без гаманців, груп і порогів. Реальні дані: покладіть wallet-radar.db"
  warn "або seed-файли в ./seed, виконайте 'docker compose down -v' і 'docker compose up'."
  WR_DB="$tmp" wr-import init
fi

# Журнал WAL мусить бути злитий в основний файл: інакше частина даних лишилась би в $tmp-wal,
# який ми не публікуємо.
for side in "$tmp-wal" "$tmp-shm" "$tmp-journal"; do
  if [ -e "$side" ]; then
    die "після побудови лишився $side — база не закрита чисто, не публікую."
  fi
done
[ -s "$tmp" ] || die "побудована база порожня — не публікую."

# --- 3. Публікація без перезапису --------------------------------------------------------
# `ln` (жорстке посилання) падає, якщо $db уже існує: на відміну від mv/cp, чужу базу не затре.
if ln "$tmp" "$db" 2>/dev/null; then
  log "створено $db"
else
  die "$db з'явився під час роботи (паралельний запуск?). Свою копію відкидаю, наявну не чіпаю."
fi
