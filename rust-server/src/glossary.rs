/// Питання схоже на прохання пояснити термін?
pub fn is_definition_question(q: &str) -> bool {
    let ql = q.to_lowercase();
    const MARKERS: &[&str] = &[
        "що таке", "шо таке", "що означа", "поясни", "поясніть", "розтлумач",
        "як рахується", "як розраховується", "як обчислюється", "як визначається",
        "дай визначення", "визначення", "що мається на увазі", "як це працює",
        "хто такий", "хто такі", "як відрізня", "як розрізня", "за якими ознаками",
        "які ознаки", "чим відрізня", "як ви визнача", "як визнача", "чим є",
        "что такое", "объясни", "как считается", "определение",
        "what is", "what does", "explain", "define", "how is it calculated",
    ];
    MARKERS.iter().any(|m| ql.contains(m))
}

/// Знайти термін у питанні. Перший збіг за порядком TERMS (специфічніші — вище).
pub fn find_term(q: &str) -> Option<&'static Term> {
    let ql = q.to_lowercase();
    TERMS.iter().find(|t| t.triggers.iter().any(|tr| ql.contains(tr)))
}

/// Перелік канонічних назв — показуємо, коли термін не впізнано.
pub fn known_terms() -> Vec<&'static str> {
    TERMS.iter().map(|t| t.canon).collect()
}

/// Записати питання, на яке глосарій не мав відповіді — це матеріал для доповнення.
/// Тихо ігнорує помилки запису: прогалина в журналі не має ламати відповідь користувачу.
pub fn log_gap(dataset_dir: &str, question: &str, kind: &str) {
    let path = format!("{}/qa-gaps.jsonl", dataset_dir.trim_end_matches('/'));
    let line = json!({
        "q": question,
        "kind": kind,
        "ts": std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_secs())
            .unwrap_or(0),
    });
    if let Ok(mut f) = std::fs::OpenOptions::new().create(true).append(true).open(&path) {
        let _ = writeln!(f, "{}", line);
    }
}

/// Головний вхід: якщо це питання про термін — повернути готову відповідь.
/// `None` означає «це не про терміни», і питання йде звичайним конвеєром.
/// Тільки ЗНАЙДЕНИЙ термін. Викликається ПЕРШИМ: якщо визначення є — віддаємо його.
/// Відмова сюди не входить навмисно — інакше глосарій блокував би базу знань
/// на питаннях типу «як визначається стан активу», де відповідь є, але не як термін.
pub fn try_answer_found(question: &str) -> Option<Value> {
    if !is_definition_question(question) {
        return None;
    }
    find_term(question).map(|t| {
        json!({
            "configured": true,
            "source": "glossary",
            "term": t.canon,
            "answer": format!("{}\n\n{}\n\nДжерело визначення: {}", t.short, t.detail, t.source),
        })
    })
}

pub fn try_answer(question: &str, dataset_dir: &str) -> Option<Value> {
    if !is_definition_question(question) {
        return None;
    }
    match find_term(question) {
        Some(t) => Some(json!({
            "configured": true,
            "source": "glossary",
            "term": t.canon,
            "answer": format!("{}\n\n{}\n\nДжерело визначення: {}", t.short, t.detail, t.source),
        })),
        None => {
            // Питання про визначення, але терміна нема — чесно кажемо й логуємо прогалину.
            log_gap(dataset_dir, question, "unknown_term");
            let list = known_terms().join(" · ");
            Some(json!({
                "configured": true,
                "source": "glossary",
                "term": Value::Null,
                "answer": format!(
                    "Такого терміна в моєму глосарії немає — не хочу вигадувати визначення.\n\n\
Ось поняття, які я можу пояснити точно:\n{}",
                    list
                ),
            }))
        }
    }
}

