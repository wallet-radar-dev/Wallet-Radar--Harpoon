/// server/cex.js — CEX.has(addr.toLowerCase())
///
/// Перелік із 40 адрес переїхав у SQLite під тегом `cex:rows`. Тег прив'язаний
/// до файлу навмисно: інші модулі мають СВОЇ переліки біржових адрес, які
/// частково перетинаються з цим, і злиття їх в один тихо розширило б кожен.
pub fn is_cex(addr: &str) -> bool {
    wr_store::snapshot().wallet_has_tag("eth", addr, "cex:rows")
}
